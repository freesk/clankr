/** Whether the cell at (column, row) of the character's glyph is ink. Unknown characters are blank. */
export function isInk(character: string, column: number, row: number): boolean {
  const rows = glyphRows[character.toUpperCase()]?.split(" ");
  return rows?.[row]?.[column] === "#";
}

export function isSupportedCharacter(character: string): boolean {
  return character.toUpperCase() in glyphRows;
}
